/**
 * A boks as something to sit through rather than to get through: the text, a
 * voice reading it, and a picture that changes as it goes.
 *
 * This is a prototype behind the admin flag, built to be shown rather than
 * shipped. It is worth saying what is real and what is staged, so nobody
 * demonstrates it and then promises the wrong thing:
 *
 * - The voice is real, and it is the browser's own (`speechSynthesis`). It
 *   costs nothing and works offline, and it sounds like what it is. A studio
 *   voice is an API and a bill, and that is a decision to take after this
 *   question is answered, not before.
 * - The pictures are real and are drawn here from the boks's id, not
 *   generated by a model and not fetched. See `scene-art.tsx`.
 * - Nothing is recorded. The reading clock, the outcomes and the feed are
 *   untouched by this screen, so an evening of demoing does not land in the
 *   recommendation data as thirty finished boks.
 */

type Phase = "cover" | "playing" | "ended";

/**
 * Two scene layers, so one picture dissolves into the next.
 *
 * A cut between scenes reads as a glitch at this size; a dissolve reads as a
 * film. The outgoing layer is kept mounted for the length of the fade and then
 * dropped, so there are never more than two skylines on the page.
 */
function Backdrop({
  seed,
  scene,
  sceneCount,
  storyId,
}: {
  seed: number;
  scene: number;
  sceneCount: number;
  storyId: string;
}) {
  const [layers, setLayers] = useState([{ scene, key: 0 }]);
  const nextKey = useRef(0);

  useEffect(() => {
    setLayers((current) => {
      if (current[current.length - 1].scene === scene) return current;
      nextKey.current += 1;
      return [...current.slice(-1), { scene, key: nextKey.current }];
    });
    const timer = window.setTimeout(() => setLayers((current) => current.slice(-1)), 1200);
    return () => window.clearTimeout(timer);
  }, [scene]);

  return (
    <>
      {layers.map((layer, index) => (
        <SceneArt
          key={layer.key}
          seed={seed}
          scene={layer.scene}
          sceneCount={sceneCount}
          storyId={storyId}
          className={`cinema__backdrop ${index < layers.length - 1 ? "cinema__backdrop--leaving" : ""}`}
        />
      ))}
    </>
  );
}

