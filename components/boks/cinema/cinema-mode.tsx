/** Cyrillic against Latin. The catalogue holds exactly these two. */
function languageOf(text: string) {
  const sample = text.slice(0, 2000);
  const cyrillic = (sample.match(/[А-Яа-яЁё]/g) ?? []).length;
  const latin = (sample.match(/[A-Za-z]/g) ?? []).length;
  return cyrillic > latin ? "ru" : "en";
}

export function CinemaMode({
  story,
  liked,
  onLike,
  onNext,
  onClose,
}: {
  story: Story;
  liked: boolean;
  onLike: () => void;
  onNext: () => void;
  onClose: () => void;
}) {
  const language = useMemo(() => languageOf(story.body), [story.body]);
  const words = copy[language];
  const plan = useMemo(() => planScenes({ id: story.id, text: story.body }), [story.id, story.body]);
  const totalSeconds = useMemo(
    () => estimateNarrationSeconds(plan.spoken, language),
    [plan.spoken, language]
  );
  const charactersPerSecond = Math.max(1, plan.spoken.length / totalSeconds);
  const picture = sceneImageFor(story.id, 0);

  const [phase, setPhase] = useState<Phase>("cover");
  const [progress, setProgress] = useState<NarratorState>({
    line: 0,
    elapsedSeconds: 0,
    totalSeconds,
    speaking: false,
    done: false,
  });
  const narrator = useRef<Narrator | null>(null);

  /**
   * The recording for this boks, if there is one. Fetched on open rather than
   * on first play, so pressing the button starts the voice instead of starting
   * a download.
   */
  const track = narrationTrackFor(story.id);
  const [lineStarts, setLineStarts] = useState<number[] | null>(null);
  useEffect(() => {
    if (!track) return;
    let cancelled = false;
    void fetch(track.alignment)
      .then((response) => (response.ok ? (response.json() as Promise<NarrationAlignment>) : null))
      .then((alignment) => {
        if (cancelled || !alignment) return;
        // Null when the words and the recording have drifted apart: better the
        // browser voice than a highlight in the wrong place.
        setLineStarts(lineStartTimes(plan.lines, alignment));
      })
      .catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, [track, plan.lines]);

  useEffect(() => {
    primeVoices();
    return () => narrator.current?.stop();
  }, []);

  /**
   * Fetch every picture while the cover is still up.
   *
   * They are about 380KB each and the scene changes on a dissolve, so one that
   * begins downloading when its scene starts arrives after the scene does -
   * the crossfade would land on nothing. Two minutes of reading is plenty of
   * time to have fetched all six, and the browser cache serves them instantly
   * when their turn comes.
   */
  useEffect(() => {
    const warmed = sceneImagesFor(story.id).map((src) => {
      const image = new Image();
      image.src = src;
      return image;
    });
    return () => warmed.forEach((image) => { image.src = ""; });
  }, [story.id]);

  // Escape closes, as it does for every other sheet in the reader.
  useEffect(() => {
    function onKey(event: KeyboardEvent) {
      if (event.key === "Escape") {
        event.stopPropagation();
        close();
      }
    }
    window.addEventListener("keydown", onKey, true);
    return () => window.removeEventListener("keydown", onKey, true);
  });

  function ensureNarrator() {
    if (!narrator.current) {
      narrator.current =
        track && lineStarts
          ? createAudioNarrator({
              audioUrl: track.audio,
              lineStarts,
              estimatedSeconds: totalSeconds,
            })
          : createNarrator({ lines: plan.lines, language, charactersPerSecond, totalSeconds });
      narrator.current.subscribe((next) => {
        setProgress(next);
        if (next.done) setPhase("ended");
      });
    }
    return narrator.current;
  }

  function begin() {
    setPhase("playing");
    ensureNarrator().play();
  }

  function close() {
    narrator.current?.stop();
    narrator.current = null;
    onClose();
  }

  // The narrator knows which line it is on - the recording to the character,
  // the browser voice because it speaks one line at a time.
  const line = progress.done ? plan.lines.length - 1 : progress.line;
  const scene = sceneAtLine(plan.sceneStarts, line);
  const elapsed = progress.elapsedSeconds;
  const total = progress.totalSeconds || totalSeconds;
  const fraction = total > 0 ? Math.min(1, elapsed / total) : 0;

  return (
    <div className="cinema" role="dialog" aria-modal="true" aria-label={story.title}>
      <Backdrop
        seed={plan.seed}
        scene={phase === "cover" ? 0 : scene}
        sceneCount={plan.sceneStarts.length}
        storyId={story.id}
      />

      <button type="button" className="cinema__close" onClick={close} aria-label={words.close}>
        <X className="size-5" />
      </button>

      {phase === "cover" && (
        <div className="cinema__cover">
          <p className="cinema__author">{story.authorName || "boks"}</p>
          <h1 className="cinema__title">{story.title}</h1>
          <span className="cinema__rule" aria-hidden="true" />
          {/* The length of the reading, not of the reading-by-eye estimate the
              feed shows. The cover promised "5 minutes" over a player that then
              ran for 6:30. */}
          <p className="cinema__meta">{words.minutes(Math.max(1, Math.round(totalSeconds / 60)))}</p>
          <button type="button" className="cinema__primary" onClick={begin}>
            {words.listen}
          </button>
          {!track && !speechSupported() && <p className="cinema__note">{words.silent}</p>}
          {/* A piece that has its own pictures and its own voice is one of
              ours, made for this text, and says so as a mark rather than as a
              technical note. A piece still wearing the shared stand-in cannot
              claim that, and says what it actually is instead. */}
          {picture.placeholder ? (
            <p className="cinema__stamp">{words.placeholder}</p>
          ) : (
            <p className="cinema__series">boks series</p>
          )}
        </div>
      )}

      {phase === "playing" && (
        <>
          {/* Where the story is, as a column of scenes rather than a number. */}
          <ol className="cinema__scenes" aria-hidden="true">
            {plan.sceneStarts.map((start, index) => (
              <li key={start} className={index === scene ? "is-current" : index < scene ? "is-past" : ""} />
            ))}
          </ol>

          <div className="cinema__stage">
            <div className="cinema__card">
              {[line - 1, line, line + 1].map((index) => {
                const entry = plan.lines[index];
                if (!entry) return <p key={index} className="cinema__line cinema__line--empty" />;
                return (
                  <p key={index} className={`cinema__line ${index === line ? "is-current" : ""}`}>
                    <span>{entry.text}</span>
                  </p>
                );
              })}
            </div>

            <div className="cinema__transport">
              <div className="cinema__bar" role="presentation">
                <span className="cinema__bar-fill" style={{ width: `${fraction * 100}%` }} />
                <span className="cinema__bar-head" style={{ left: `${fraction * 100}%` }} />
              </div>
              <div className="cinema__times">
                <span>{formatClock(elapsed)}</span>
                <span>{formatClock(total)}</span>
              </div>
              <button
                type="button"
                className="cinema__transport-button"
                onClick={() => (progress.speaking ? narrator.current?.pause() : narrator.current?.resume())}
                aria-label={progress.speaking ? words.pause : words.play}
              >
                {progress.speaking ? <Pause className="size-6" /> : <Play className="size-6" />}
              </button>
            </div>
          </div>
        </>
      )}

      {phase === "ended" && (
        <div className="cinema__ended">
          <h2 className="cinema__ended-title">{words.ended}</h2>
          <p className="cinema__ended-sub">{words.endedSub}</p>
          <div className="cinema__ended-actions">
            <button
              type="button"
              className="cinema__primary"
              onClick={() => {
                setPhase("playing");
                ensureNarrator().restart();
              }}
            >
              <RotateCcw className="size-4" />
              {words.again}
            </button>
            <button type="button" className="cinema__secondary" onClick={onLike}>
              {liked ? <BookmarkCheck className="size-4" /> : <Bookmark className="size-4" />}
              {liked ? words.saved : words.save}
            </button>
            <button
              type="button"
              className="cinema__secondary"
              onClick={() => {
                narrator.current?.stop();
                narrator.current = null;
                onNext();
              }}
            >
              <ArrowRight className="size-4" />
              {words.next}
            </button>
          </div>
        </div>
      )}
    </div>
  );
}
