#!/usr/bin/env node
// Writes the migration that publishes an edition of the author offer and the
// two consents (`docs/author-agreements.md`): the texts in docs/legal/author/
// go into public.boks_legal_documents word for word, under one version.
//
//   node scripts/legal/author-terms-sql.mjs 2026-11-23 20261123110000
//   node scripts/legal/author-terms-sql.mjs 2026-11-23.2 20261123160000 processing
//
// The optional list (offer, processing, distribution) publishes only those
// documents in the new edition; the others stay in force as they are.
// A published edition is never changed: a new text is a new version and a new
// migration. Authors who accepted the old one keep it (`?v=` on its page).
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const [version, stamp, ...only] = process.argv.slice(2);
if (!/^\d{4}-\d{2}-\d{2}(\.\d+)?$/.test(version ?? "") || !/^\d{14}$/.test(stamp ?? "")) {
  console.error("usage: author-terms-sql.mjs <version YYYY-MM-DD> <migration stamp YYYYMMDDHHMMSS>");
  process.exit(2);
}
const all = [
  ["author_offer", "offer"],
  ["author_pd_processing", "processing"],
  ["author_pd_distribution", "distribution"],
];
const unknown = only.filter((name) => !all.some(([, file]) => file === name));
if (unknown.length) {
  console.error(`unknown document: ${unknown.join(", ")}`);
  process.exit(2);
}
const docs = only.length ? all.filter(([, file]) => only.includes(file)) : all;
const dollar = "$";
let sql = `-- ${docs.map(([, file]) => file).join(", ")}: edition ${version} (generated by\n-- scripts/legal/author-terms-sql.mjs from docs/legal/author/; do not edit by hand).\n`;
for (const [kind, file] of docs) {
  const body = readFileSync(new URL(`../../docs/legal/author/${file}.md`, import.meta.url), "utf8").replace(/\r\n?/g, "\n").trim() + "\n";
  if (body.includes("—")) throw new Error(`${file}.md has a long dash`);
  const title = body.split("\n")[0].replace(/^# /, "").trim();
  let tag = "doc";
  while (body.includes(dollar + tag + dollar)) tag += "x";
  const q = (text) => dollar + tag + dollar + text + dollar + tag + dollar;
  const hash = createHash("sha256").update(body, "utf8").digest("hex");
  sql += `\n-- ${file}.md, sha256 ${hash}\ninsert into public.boks_legal_documents (kind, version, title, body)\nvalues ('${kind}', '${version}', ${q(title)}, ${q(body)})\non conflict (kind, version) do nothing;\n`;
}
const out = new URL(`../../supabase/migrations/${stamp}_boks_author_terms_${version.replace(/\D/g, "")}.sql`, import.meta.url);
writeFileSync(out, sql);
console.log(out.pathname);
